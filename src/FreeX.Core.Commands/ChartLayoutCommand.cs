public sealed partial class SetChartLayoutCommand : IWorkbookCommand
{
    private readonly SheetId _sheetId;
    private readonly Guid _chartId;
    private readonly ChartLayoutOptions _options;
    private ChartLayoutOptions? _previous;

    public string Label => "Format Chart Layout";

    public SetChartLayoutCommand(SheetId sheetId, Guid chartId, ChartLayoutOptions options)
    {
        _sheetId = sheetId;
        _chartId = chartId;
        _options = options;
    }

    public CommandOutcome Apply(ICommandContext ctx)
    {
        var sheet = ctx.GetSheet(_sheetId);
        if (!ChartCommandGuards.TryFindChart(sheet, _chartId, out var chart))
            return ChartCommandGuards.ChartNotFound();

        // R112-model-drawing-object-lock-1-1: layer in the per-chart Locked override so an
        // author-unlocked chart's layout stays editable even while the sheet blocks "Edit objects".
        if (ChartCommandGuards.RejectIfEditObjectsBlocked(sheet, chart) is { } protectedOutcome)
            return protectedOutcome;

        _previous = Capture(chart);
        ApplyOptions(chart, _options);
        return new CommandOutcome(true, AffectedCells: [chart.DataRange.Start]);
    }

    public void Revert(ICommandContext ctx)
    {
        if (_previous is null)
            return;

        if (!ChartCommandGuards.TryFindChart(ctx.GetSheet(_sheetId), _chartId, out var chart))
            return;

        RestoreLayout(chart, _previous);
    }

